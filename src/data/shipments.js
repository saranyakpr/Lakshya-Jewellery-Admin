export const trackingSteps = ['Order Placed', 'Shipped', 'Out for Delivery', 'Delivered']

const statusByStep = {
  1: 'Order Confirmed',
  2: 'Shipped',
  3: 'In Transit',
  4: 'Delivered',
}

function buildShipment({
  trackingId,
  orderId,
  customerName,
  customerEmail,
  courier,
  completedSteps,
  city,
  state,
  estimatedDate,
  estimatedTime,
}) {
  return {
    trackingId,
    orderId,
    customerName,
    customerEmail,
    courier,
    completedSteps,
    status: statusByStep[completedSteps],
    city,
    state,
    estimatedDate,
    estimatedTime,
    isDelivered: completedSteps >= trackingSteps.length,
  }
}

