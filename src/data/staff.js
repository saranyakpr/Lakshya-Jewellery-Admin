function initialsOf(name) {
  return name
    .split(' ')
    .map((part) => part.charAt(0))
    .join('')
    .slice(0, 2)
    .toUpperCase()
}

function buildStaff(index, fields) {
  return {
    ...fields,
    initials: initialsOf(fields.name),
    avatar: avatarPalette[index % avatarPalette.length],
  }
}

